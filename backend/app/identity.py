"""App identity and signing certificate, extracted with androguard."""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from .findings import finding

log = logging.getLogger("revdroid.identity")


def load_apk(path: Path):
    from androguard.core.apk import APK  # imported lazily: androguard is slow to import
    return APK(str(path))


def _safe(fn, default=None):
    try:
        return fn()
    except Exception as exc:  # noqa: BLE001 - malformed manifests are common; keep going
        log.warning("androguard call failed: %s", exc)
        return default


def _to_int(v: Any) -> int | None:
    try:
        return int(v)
    except (TypeError, ValueError):
        return None


def _cert_info(cert: Any) -> dict[str, Any]:
    validity = cert["tbs_certificate"]["validity"]
    pub = cert.public_key
    return {
        "subject": cert.subject.human_friendly,
        "issuer": cert.issuer.human_friendly,
        "serial_number": format(cert.serial_number, "x"),
        "not_before": validity["not_before"].native.isoformat(),
        "not_after": validity["not_after"].native.isoformat(),
        "signature_algorithm": f"{cert['signature_algorithm'].signature_algo} / {cert.hash_algo}",
        "public_key": f"{pub.algorithm.upper()} {pub.bit_size} bit",
        "sha1": cert.sha1.hex(),
        "sha256": cert.sha256.hex(),
        "self_signed": cert.self_signed in ("yes", "maybe"),
    }


def extract_identity(apk) -> dict[str, Any]:
    files = _safe(apk.get_files, []) or []
    certs = _safe(apk.get_certificates, []) or []
    return {
        "package_name": _safe(apk.get_package),
        "app_name": _safe(apk.get_app_name),
        "version_code": _safe(apk.get_androidversion_code),
        "version_name": _safe(apk.get_androidversion_name),
        "min_sdk": _to_int(_safe(apk.get_min_sdk_version)),
        "target_sdk": _to_int(_safe(apk.get_target_sdk_version)),
        "main_activity": _safe(apk.get_main_activity),
        "signing": {
            "v1": bool(_safe(apk.is_signed_v1, False)),
            "v2": bool(_safe(apk.is_signed_v2, False)),
            "v3": bool(_safe(apk.is_signed_v3, False)),
            "certificates": [c for c in (_safe(lambda c=c: _cert_info(c)) for c in certs) if c],
        },
        "dex_count": sum(1 for f in files if f.startswith("classes") and f.endswith(".dex")),
        "native_abis": sorted({f.split("/")[1] for f in files if f.startswith("lib/") and f.count("/") >= 2}),
        "file_count": len(files),
    }


def signing_findings(identity: dict[str, Any]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    sig = identity["signing"]
    certs = sig["certificates"]
    if not certs:
        out.append(finding(
            id="SIGN-NONE", title="APK is not signed", severity="medium", category="signing", source="signing",
            description="No signing certificate was found. Android refuses to install unsigned APKs, so this "
                        "is probably a build artefact rather than a release.",
            recommendation="Sign release builds with a private release key using apksigner (v2+ scheme)."))
        return out
    for c in certs:
        if "Android Debug" in c.get("subject", ""):
            out.append(finding(
                id="SIGN-DEBUG", title="Signed with the Android debug certificate", severity="high",
                category="signing", source="signing", evidence=c.get("subject"), cwe="CWE-321",
                masvs="MASVS-CODE-1",
                description="The debug keystore is generated by every Android SDK install and is not protected. "
                            "Debug-signed builds are not meant for distribution.",
                recommendation="Sign release builds with a private release key kept out of source control."))
        algo = c.get("signature_algorithm", "").lower()
        if "md5" in algo or "sha1" in algo:
            out.append(finding(
                id="SIGN-WEAK-ALGO", title="Certificate uses a weak signature hash", severity="low",
                category="signing", source="signing", evidence=c.get("signature_algorithm"), cwe="CWE-328",
                description="MD5 and SHA-1 are collision-prone hash functions.",
                recommendation="Use a SHA-256 signing key; APK Signature Scheme v3 supports key rotation."))
    min_sdk = identity.get("min_sdk") or 1
    if sig["v1"] and not (sig["v2"] or sig["v3"]) and min_sdk < 24:
        out.append(finding(
            id="SIGN-JANUS", title="Only v1 (JAR) signature on Android < 7.0 (Janus)", severity="medium",
            category="signing", source="signing", cwe="CWE-347", masvs="MASVS-CODE-1",
            evidence=f"minSdk={min_sdk}, v1 scheme only",
            description="With only the v1 scheme, Android 5.0 to 7.0 devices are exposed to the Janus flaw "
                        "(CVE-2017-13156), which lets an attacker prepend DEX code without breaking the signature.",
            recommendation="Enable APK Signature Scheme v2/v3 in the release signing config."))
    return out
